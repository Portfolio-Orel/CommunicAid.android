/** Extra design tokens not covered by the Material3 version used in this project. */
@Immutable
data class ExtendedColors(
    val cardSurface: Color,
    val cardBorder: Color,
    val success: Color,
    val successContainer: Color,
)

private val LightExtended = ExtendedColors(
    cardSurface = light_cardSurface,
    cardBorder = light_cardBorder,
    success = light_success,
    successContainer = light_successContainer,
)

private val DarkExtended = ExtendedColors(
    cardSurface = dark_cardSurface,
    cardBorder = dark_cardBorder,
    success = dark_success,
    successContainer = dark_successContainer,
)

val LocalExtendedColors = staticCompositionLocalOf { LightExtended }

/** Convenience accessor: `AppTheme.extended.cardSurface` */
object AppTheme {
    val extended: ExtendedColors
        @Composable get() = LocalExtendedColors.current
}

@Composable
fun MyMessagesTheme(
    useDarkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colors = if (useDarkTheme) DarkColors else LightColors
    val extended = if (useDarkTheme) DarkExtended else LightExtended

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            window.statusBarColor = colors.background.toArgb()
            window.navigationBarColor = colors.background.toArgb()
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !useDarkTheme
                isAppearanceLightNavigationBars = !useDarkTheme
            }
        }
    }

    CompositionLocalProvider(LocalExtendedColors provides extended) {
        MaterialTheme(
            colorScheme = colors,
            typography = Typography,
            shapes = AppShapes,
            content = content
        )
    }
}
